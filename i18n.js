let currentLang = 'en';

function getStoredLanguage() {
    const stored = localStorage.getItem(I18N_STORAGE_KEY);
    return stored === 'mr' || stored === 'en' ? stored : 'en';
}

function t(key) {
    return TRANSLATIONS[currentLang][key] || TRANSLATIONS.en[key] || key;
}

/** Convert an integer to locale-appropriate numeral string.
 *  In Marathi mode renders Devanagari digits (०१२…), otherwise plain ASCII. */
function toLocalNum(n) {
    if (currentLang !== 'mr') return String(n);
    const DEVA = ['०','१','२','३','४','५','६','७','८','९'];
    return String(n).replace(/[0-9]/g, function(d) { return DEVA[+d]; });
}

function setLanguage(lang) {
    if (lang !== 'en' && lang !== 'mr') return;
    currentLang = lang;
    localStorage.setItem(I18N_STORAGE_KEY, lang);
    document.documentElement.lang = lang === 'mr' ? 'mr' : 'en';
    document.body.classList.toggle('lang-mr', lang === 'mr');

    const meta = document.querySelector('meta[name="description"]');
    if (meta) meta.setAttribute('content', t('metaDescription'));
    document.title = t('pageTitle');

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const value = t(key);
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
            el.placeholder = value;
        } else {
            el.textContent = value;
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });

    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
        el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });

    const langEn = document.getElementById('langEn');
    const langMr = document.getElementById('langMr');
    if (langEn && langMr) {
        const isEn = lang === 'en';
        langEn.classList.toggle('lang-active', isEn);
        langMr.classList.toggle('lang-active', !isEn);
        langEn.setAttribute('aria-pressed', isEn);
        langMr.setAttribute('aria-pressed', !isEn);
    }

    if (typeof window.onLanguageChange === 'function') {
        window.onLanguageChange(lang);
    }
}

function transliterateWord(word) {
    const s = word.toLowerCase().replace(/[^a-z]/g, '');
    if (!s) return word;

    let out = '';
    let i = 0;

    while (i < s.length) {
        let consonant = '';
        for (const len of [3, 2, 1]) {
            const chunk = s.substring(i, i + len);
            if (CONSONANT_MR[chunk]) {
                consonant = CONSONANT_MR[chunk];
                i += len;
                break;
            }
        }

        if (!consonant) {
            // No consonant found — treat as a standalone vowel (e.g. word-initial 'a', 'e', 'i')
            let found = false;
            for (const len of [2, 1]) {
                const v = s.substring(i, i + len);
                if (VOWEL_STANDALONE_MR[v]) {
                    out += VOWEL_STANDALONE_MR[v];
                    i += len;
                    found = true;
                    break;
                }
            }
            if (!found) i += 1;
            continue;
        }

        let vowel = 'a';
        for (const len of [2, 1]) {
            const v = s.substring(i, i + len);
            if (Object.prototype.hasOwnProperty.call(VOWEL_MATRA_MR, v)) {
                vowel = v;
                i += len;
                break;
            }
        }

        out += consonant + (VOWEL_MATRA_MR[vowel] ?? '');
    }

    return out || word;
}

function transliterateLatin(text) {
    if (!text) return text;
    return text
        .trim()
        .split(/\s+/)
        .map(part => transliterateWord(part))
        .join(' ');
}

function translateAreaLabel(area) {
    if (currentLang === 'en' || !area) return area;

    const lower = area.toLowerCase().trim();
    // Exact match for the full area string
    if (AREA_LABELS_MR[lower]) return AREA_LABELS_MR[lower];

    // Word-by-word: translate known words, transliterate the rest.
    // Words containing digits (e.g. "N4") or single characters (e.g. "N") are kept as-is.
    const words = area.trim().split(/\s+/);
    const result = words.map(function(word) {
        // Strip surrounding punctuation (commas, dots, dashes) but preserve for rejoining
        const leadingPunct  = word.match(/^[,.\-–—;:]+/) ? word.match(/^[,.\-–—;:]+/)[0] : '';
        const trailingPunct = word.match(/[,.\-–—;:]+$/) ? word.match(/[,.\-–—;:]+$/)[0] : '';
        const core = word.slice(leadingPunct.length, word.length - trailingPunct.length);
        if (!core || /\d/.test(core) || core.length === 1) return word;
        const cl = core.toLowerCase();
        if (AREA_LABELS_MR[cl]) return leadingPunct + AREA_LABELS_MR[cl] + trailingPunct;
        return leadingPunct + transliterateWord(core) + trailingPunct;
    });
    return result.join(' ');
}

function translateProviderName(name) {
    if (currentLang === 'en' || !name) return name;
    return name.trim().split(/\s+/).map(function(word) {
        const wl = word.toLowerCase();
        // 1. Known name/surname dictionary
        if (PROVIDER_NAME_PARTS_MR[wl]) return PROVIDER_NAME_PARTS_MR[wl];
        // 2. Service word in a business name (e.g. "Furniture", "Plumber")
        if (SERVICE_LABELS_MR[wl]) return SERVICE_LABELS_MR[wl];
        // 3. Fallback: phonetic transliteration
        return transliterateWord(word);
    }).join(' ');
}

function translateServiceLabel(service) {
    if (currentLang === 'en' || !service) return service;
    const lower = service.toLowerCase().trim();
    // Exact match first
    if (SERVICE_LABELS_MR[lower]) return SERVICE_LABELS_MR[lower];
    // Word-boundary match: avoids false hits like "contractor" matching "ac"
    for (const [keyword, label] of Object.entries(SERVICE_LABELS_MR)) {
        const escaped = keyword.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        if (new RegExp('\\b' + escaped + '\\b').test(lower)) return label;
    }
    return transliterateLatin(service);
}

function translateStatusLabel(status) {
    if (currentLang === 'en' || !status) return status;
    if (status === 'Active') return t('statusActive');
    return status;
}

function initI18n() {
    currentLang = getStoredLanguage();
    setLanguage(currentLang);

    const langEn = document.getElementById('langEn');
    const langMr = document.getElementById('langMr');
    if (langEn) langEn.addEventListener('click', () => setLanguage('en'));
    if (langMr) langMr.addEventListener('click', () => setLanguage('mr'));
}
